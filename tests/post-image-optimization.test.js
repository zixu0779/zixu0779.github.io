const assert = require('node:assert/strict');
const { optimizePostImages, optimizeListImages } = require('../scripts/post-image-optimization');
const url = 'https://res.cloudinary.com/sycamore/image/upload/v123/Typora/code.png';
const img = `<img data-src="${url}" loading="lazy" width="1000" height="500" style="--article-image-width:320px;--article-image-ratio:1000/500;">`;
const wrap = image => `<article class="post block"><div class="md">${image}</div></article>`;
const raw = optimizePostImages(wrap(img));
const result = require('hexo-util').unescapeHTML(raw);
assert.ok(result.includes(`data-original-src="${url}"`));
assert.ok(result.includes('w_320/v123/Typora/code.png 320w'));
assert.ok(result.includes('w_640/v123/Typora/code.png 640w'));
assert.ok(result.includes('width="1000" height="500"'));
assert.ok(result.includes('--article-image-width:320px;--article-image-ratio:1000/500;'));
assert.ok(!result.includes(' data-src='));
assert.equal(optimizePostImages(raw), raw);
const versionless = require('hexo-util').unescapeHTML(optimizePostImages(wrap(img.replace('/v123/', '/'))));
assert.ok(versionless.includes('w_320/Typora/code.png 320w'));
assert.ok(versionless.includes('data-original-src="https://res.cloudinary.com/sycamore/image/upload/Typora/code.png"'));
assert.equal(optimizePostImages(img), img);
assert.equal(optimizePostImages(wrap(img.replace('code.png','animation.gif'))), wrap(img.replace('code.png','animation.gif')));
assert.ok(!optimizePostImages(wrap(img.replace('width="1000"', 'width="133"'))).includes('w_640/'));
const list = optimizeListImages(`<img data-src="${url}" loading="lazy" alt="article cover">`);
assert.ok(list.includes('q_auto:good')); assert.ok(list.includes('srcset='));
console.log('Original links, display dimensions, small-image bounds, GIF exclusion and list optimization verified');
